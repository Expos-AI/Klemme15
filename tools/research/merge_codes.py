#!/usr/bin/env python3
"""Merge researched fault-code files into src/Klemme15.Data/db/bmw-codes.json.

Each research file is a JSON array of {module, code, text, hint?, component?, engines?, confidence, sources[]}
written to tools/research/RESEARCH-BRIEF.md. Run from the repository root:  python3 tools/research/merge_codes.py
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
RESEARCH = ROOT / "tools" / "research"
OUT = ROOT / "src" / "Klemme15.Data" / "db" / "bmw-codes.json"
FILES = ["dme-n52.json", "dme-n54-n55.json", "chassis.json", "body.json", "manual.json"]
KNOWN_MODULES = {m["id"] for m in json.loads((ROOT / "src/Klemme15.Data/db/modules.json").read_text())["modules"]}
COMPONENTS = set(json.loads((ROOT / "src/Klemme15.Data/db/components.json").read_text())["components"])

entries = {}
skipped = []
for name in FILES:
    path = RESEARCH / name
    if not path.exists():
        continue
    for e in json.loads(path.read_text()):
        code = e["code"].upper()
        module = e["module"]
        if not re.fullmatch(r"[0-9A-F]{4}", code) or not e.get("sources") or not e.get("text"):
            skipped.append((name, module, code, "incomplete")); continue
        if module not in KNOWN_MODULES:
            skipped.append((name, module, code, "unknown module")); continue
        if e.get("component") and e["component"] not in COMPONENTS:
            e = {**e, "component": None}
        key = (module, code)
        new = {
            "text": e["text"].strip(),
            "hint": (e.get("hint") or "").strip() or None,
            "component": e.get("component"),
            "engines": e.get("engines") or None,
            "confidence": e.get("confidence", "medium"),
            "sources": list(dict.fromkeys(e["sources"])),
            "seenOn": e.get("seenOn") or None,
        }
        old = entries.get(key)
        if old is None:
            entries[key] = new; continue
        # Same code researched twice: keep the stronger text, pool the evidence.
        better = new if (new["confidence"] == "high" and old["confidence"] != "high") else old
        merged = dict(better)
        merged["sources"] = list(dict.fromkeys(old["sources"] + new["sources"]))
        merged["engines"] = None if (old["engines"] is None or new["engines"] is None) else sorted(set(old["engines"]) | set(new["engines"]))
        merged["hint"] = better["hint"] or old["hint"] or new["hint"]
        merged["component"] = better["component"] or old["component"] or new["component"]
        merged["seenOn"] = sorted(set((old["seenOn"] or []) + (new["seenOn"] or []))) or None
        if len(merged["sources"]) >= 2: merged["confidence"] = "high"
        entries[key] = merged

# Codes read with Klemme15 on real cars (from user scan reports).
SEEN = {
    "E90 325i 2006": [("E9x.DSC", c) for c in ("5E18", "5E40", "5E1A")] + [("E9x.CAS", c) for c in ("A111", "A0AF", "A0A9", "A119")]
                     + [("E9x.KOMBI", c) for c in ("9315", "A3B9", "A3B2")] + [("E9x.JBE", "A731")] + [("E9x.FZD", c) for c in ("A669", "A670")],
}
for car, keys in SEEN.items():
    for key in keys:
        if key in entries:
            entries[key]["seenOn"] = sorted(set((entries[key].get("seenOn") or []) + [car]))

modules = {}
for (module, code), e in sorted(entries.items()):
    modules.setdefault(module, {})[code] = {k: v for k, v in e.items() if v is not None}

doc = {
    "$comment": ("BMW-specific fault codes, keyed by module id then 4-digit hex code. Every text is written in our own words, "
                 "never copied from BMW software or documents. 'confidence': high = two or more independent sources agree, "
                 "medium = one specific source. 'engines' limits a meaning to those engines (the same code can differ between "
                 "engine computers). 'seenOn' lists real cars where Klemme15 read the code. Generated by "
                 "tools/research/merge_codes.py from the files in tools/research; edit those, then re-run the script."),
    "modules": modules,
}
OUT.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")
total = sum(len(v) for v in modules.values())
high = sum(1 for v in modules.values() for e in v.values() if e["confidence"] == "high")
print(f"{total} codes ({high} high confidence) across {len(modules)} modules -> {OUT.relative_to(ROOT)}")
for s in skipped: print("skipped:", *s)

#!/usr/bin/env python3
"""
Adds the Klemme15 copyright and license notice to the top of every tracked .cs and .axaml file.

    python3 scripts/license-headers.py           # add missing headers
    python3 scripts/license-headers.py --check   # list files without one, exit 1 if any (for CI)

Only files tracked by git are touched, so third-party code that isn't part of the repository (EdiabasLib, fetched at
build time into external/) is never stamped. Files that already carry a header are left alone, so running it twice
changes nothing. Generated files ("<auto-generated>") are skipped.
"""
import subprocess
import sys

NOTICE = [
    "Klemme15: open-source BMW diagnostics",
    "Copyright (C) 2026 Kindric Castro",
    "",
    "This program is free software: you can redistribute it and/or modify it under the terms of the GNU General",
    "Public License as published by the Free Software Foundation, either version 3 of the License, or (at your",
    "option) any later version. This program is distributed in the hope that it will be useful, but WITHOUT ANY",
    "WARRANTY; without even the implied warranty of MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the GNU",
    "General Public License for more details. You should have received a copy of the GNU General Public License",
    "along with this program. If not, see <https://www.gnu.org/licenses/>.",
    "",
    "SPDX-License-Identifier: GPL-3.0-or-later",
]
MARKER = "SPDX-License-Identifier: GPL-3.0-or-later"


def header_for(path: str) -> str:
    if path.endswith(".axaml"):
        return "<!--\n" + "\n".join(("  " + l).rstrip() for l in NOTICE) + "\n-->\n"
    return "\n".join(("// " + l).rstrip() for l in NOTICE) + "\n\n"


def tracked() -> list[str]:
    out = subprocess.run(["git", "ls-files", "*.cs", "*.axaml"], capture_output=True, text=True, check=True).stdout
    return [p for p in out.splitlines() if not p.startswith("external/")]


def main() -> int:
    check = "--check" in sys.argv
    missing, added = [], 0
    for path in tracked():
        with open(path, encoding="utf-8-sig") as f:
            text = f.read()
        head = text[:2000]
        if MARKER in head or "<auto-generated" in head:
            continue
        if check:
            missing.append(path)
            continue
        # An XML declaration has to stay first; the comment goes after it.
        if text.startswith("<?xml"):
            end = text.index("?>") + 2
            text = text[:end] + "\n" + header_for(path) + text[end:].lstrip("\r\n")
        else:
            text = header_for(path) + text
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        added += 1
    if check:
        for p in missing:
            print(f"missing license header: {p}")
        return 1 if missing else 0
    print(f"added a header to {added} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
